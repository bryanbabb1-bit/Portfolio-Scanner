class PortfolioConfig(BaseModel):
    """The full editable portfolio config persisted to portfolio.json."""
    owner: str = "You"
    advisor_persona: str = "senior financial advisor at Charles Schwab"
    cash: float = 0.0    # uninvested buying power — counts toward total & allocation
    # symbols the client holds as long-term CONVICTIONS: accumulate on weakness,
    # never told to sell at a loss on a technical break (only if thesis breaks)
    core_convictions: list[str] = []
    # When dry powder is low, stop alerting/enriching runners + not-owned buys
    # (nothing to act on there) and only watch names you actually hold. Saves
    # Claude usage when there's no cash to deploy.
    quiet_unowned_low_cash: bool = True
    # Only fire buy/sell SIGNALS for names you actually hold or watch. The
    # discovery universe is market-wide now (~190 tickers), so scanning it for
    # slaps produces alerts on names with no place in the book. Discovery and
    # the advisor's scouting are unaffected — this gates the signal engine only.
    signals_owned_only: bool = True
    # The ONLY standing guidance the advisor gets. This replaced a generated
    # strategy document with allocation targets, guardrails and milestones —
    # that doc accumulated stale claims and ended up contradicting the live
    # brief, so it was removed. One sentence the client controls, nothing
    # derived, nothing to drift out of sync.
    risk_profile: str = (
        "Aggressive risk profile targeting double-digit annual growth, with "
        "little or no additional capital being contributed."
    )
    themes: dict[str, str] = {}
    holdings: list[Holding] = []
    watchlist: list[WatchItem] = []


