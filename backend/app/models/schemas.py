class AskRequest(BaseModel):
    """A follow-up question about a prior advisor note."""
    kind: str  # "portfolio" | "stock" | "breakout" | "strategy"
    symbol: Optional[str] = None
    question: str = Field(min_length=1, max_length=2000)
    deep: bool = False  # allow web research (slower, live news/sentiment)

    @field_validator("kind")
    @classmethod
    def _valid_kind(cls, v: str) -> str:
        v = (v or "").strip().lower()
        if v not in {"portfolio", "stock", "breakout", "strategy"}:
            raise ValueError("kind must be portfolio, stock, breakout or strategy")
        return v


class DeviceRegister(BaseModel):
    """A native-app device registering for push notifications."""
    token: str = Field(min_length=1)
    platform: Optional[str] = None  # ios | android


class WatchpointCreate(BaseModel):
    """A standing price/RSI tripwire that fires a slap alert when met."""
    symbol: str = Field(min_length=1)
    kind: str  # price_below | price_above | rsi_below | rsi_above
    level: float = Field(gt=0)
    note: str = Field(default="", max_length=300)
    side: Optional[str] = None  # buy | sell (slap styling); inferred if omitted
    confirm: str = "touch"  # "close" = only fire near/after the session close

    @field_validator("confirm")
    @classmethod
    def _valid_confirm(cls, v: str) -> str:
        v = (v or "touch").strip().lower()
        if v not in {"touch", "close"}:
            raise ValueError("confirm must be touch or close")
        return v

    @field_validator("kind")
    @classmethod
    def _valid_kind(cls, v: str) -> str:
        v = (v or "").strip().lower()
        if v not in {"price_below", "price_above", "rsi_below", "rsi_above"}:
            raise ValueError("kind must be price_below/price_above/rsi_below/rsi_above")
        return v

    @field_validator("symbol")
    @classmethod
    def _upper(cls, v: str) -> str:
        v = (v or "").strip().upper()
        if not v:
            raise ValueError("symbol required")
        return v


